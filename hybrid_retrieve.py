def resolve_path(p: str | Path, base: Path = ROOT) -> Path:
    """Absolute path for *p*; relative paths anchor at *base* (repo root by default)."""
    p = Path(p)
    return p if p.is_absolute() else (base / p).resolve()


def rel_source(path: str | Path) -> str:
    """Posix path relative to ROOT when possible (stable, display-friendly source ids)."""
    p = Path(path)
    try:
        return p.resolve().relative_to(ROOT).as_posix()
    except (ValueError, OSError):
        return p.as_posix()


def _norm_rel(p: str | Path) -> str:
    """Normalise a path for prefix comparison: relative-to-ROOT posix, no trailing slash."""
    s = rel_source(p)
    return s.rstrip("/")


@dataclass
class Chunk:
    chunk_id: int
    source: str
    text: str
    title: str = ""


def load_chunks_pickle(path: str) -> list[Chunk]:
    """Unpickle chunks safely regardless of how ``Chunk`` was originally pickled.

    ``--build`` run as a script used to pickle dataclasses defined in ``__main__``, so the
    stored class path could be ``__main__.Chunk``. Loading that from any other module raises
    ``AttributeError: module '__main__' has no attribute 'Chunk'``. Register the class under
    that name before unpickling so ``chunks.pkl`` stays readable from libraries, notebooks
    and the REPL.
    """
    main_mod = sys.modules.setdefault("__main__", sys.modules[__name__])
    if not hasattr(main_mod, "Chunk"):
        setattr(main_mod, "Chunk", Chunk)
    with open(path, "rb") as f:
        return pickle.load(f)


def save_chunks_pickle(chunks: list["Chunk"], path: str) -> None:
    """Pickle *chunks* to *path* with a module-stable class reference.

    When this file is run as a script, ``Chunk`` lives in ``__main__`` and a separate
    ``hybrid_retrieve`` module object may also exist; pickle rejects the alias unless the
    registered class is literally the same object. So alias the running module under the
    importable name first, then stamp ``__module__``.
    """
    mod = sys.modules[__name__]
    if getattr(mod, "Chunk", None) is not Chunk:
        mod.Chunk = Chunk
    if getattr(sys.modules.get("hybrid_retrieve"), "Chunk", None) is not Chunk:
        sys.modules["hybrid_retrieve"] = mod
    prev = Chunk.__module__
    Chunk.__module__ = "hybrid_retrieve"
    try:
        with open(path, "wb") as f:
            pickle.dump(chunks, f)
    finally:
        Chunk.__module__ = prev


def clean_html_file(path: str) -> tuple[str, str]:
    """Extract semantic text and title from a Unity doc HTML file.

    Uses the same content-root selector as dumpdoc.py and strips site chrome
    (nav bar, language selector, feedback widget) so boilerplate never enters
    the index. Returns (text, title).
    """
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        soup = BeautifulSoup(f.read(), "lxml")
    title = page_title(soup)
    root = content_root(soup)
    for tag in root(["script", "style", "nav", "footer", "header", "aside"]):
        tag.decompose()
    parts: list[str] = []
    for elem in root.find_all(["h1", "h2", "h3", "h4", "p", "pre", "code", "li", "td"]):
        text = elem.get_text(strip=True)
        if text:
            parts.append(text)
    return strip_boiler("\n".join(parts)), title


def chunk_text(text: str, max_len: int = 800, overlap: int = 120) -> list[str]:
    """Simple paragraph-based chunking with overlap."""
    paragraphs = [p.strip() for p in re.split(r"\n+", text) if p.strip()]
    chunks: list[str] = []
    current = ""
    for p in paragraphs:
        if len(current) + len(p) + 1 > max_len and current:
            chunks.append(current.strip())
            current = current[-overlap:] if overlap < len(current) else ""
        current += ("\n" if current else "") + p
    if current:
        chunks.append(current.strip())
    return chunks or [text[:max_len]]


def load_chunks(dirs: list[str], max_files: int | None = None) -> list[Chunk]:
    """Load HTML files from *dirs* (resolved against ROOT) and split into chunks.

    Sources are stored ROOT-relative posix so results are stable across machines/cwds.
    """
    files: list[Path] = []
    for d in dirs:
        root = resolve_path(d)
        files.extend(root.rglob("*.html"))
    if max_files:
        files = files[:max_files]
    chunks: list[Chunk] = []
    for path in tqdm(files, desc="Parsing HTML"):
        try:
            text, title = clean_html_file(str(path))
        except Exception:
            continue
        if len(text) < 50:
            continue
        src = rel_source(path)
        for c in chunk_text(text):
            chunks.append(Chunk(chunk_id=len(chunks), source=src, text=c, title=title))
    return chunks


def build_page_map(chunks: list["Chunk"]) -> dict[str, list[int]]:
    """normalised source -> chunk ids in document order (chunk_id order == append order)."""
    pages: dict[str, list[int]] = {}
    for c in chunks:
        pages.setdefault(rel_source(c.source), []).append(c.chunk_id)
    return pages


def render_snippet(
    chunk: "Chunk",
    chunks: list["Chunk"],
    page_map: dict[str, list[int]],
    width: int = 500,
) -> tuple[str, bool]:
    """Boilerplate-stripped snippet for *chunk*.

    Falls back to sibling chunks of the same page when stripping empties the text.
    Returns (snippet, truncated).
    """
    def clean(t: str) -> str:
        return strip_boiler(t).strip()

    text = clean(chunk.text)
    if not text:
        for cid in page_map.get(rel_source(chunk.source), []):
            if cid == chunk.chunk_id:
                continue
            text = clean(chunks[cid].text)
            if text:
                break
    return text[:width], len(text) > width


