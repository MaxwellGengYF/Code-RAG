# Session: everything needed to serve queries/mentions/reads, loaded once.
# --------------------------------------------------------------------------------------


class Session:
    """Loaded retriever state shared by CLI query mode, --repl and mcp_server.py."""

    def __init__(self, args, config: dict, embedder: "Embedder | None" = None):
        self.args = args
        self.config = config
        self.index_path = resolve_index_path(args, config)
        self.chunks_path = resolve_path(args.chunks_path)
        missing = [p for p in (self.chunks_path, self.index_path) if not p.exists()]
        if missing:
            raise FileNotFoundError(
                "artefact not found: " + ", ".join(str(m) for m in missing) +
                f"\n  cwd: {Path.cwd()}\n  repo root: {ROOT}\n"
                f"Paths resolve against the repo root — run from there, set "
                f"UNITY_DOCS_ROOT, or rebuild with --build (takes a few minutes)."
            )
        t0 = time.time()
        self.chunks: list[Chunk] = load_chunks_pickle(str(self.chunks_path))
        self.index = InvertedIndex()
        self.index.load(str(self.index_path))
        self.tokenizer = get_tokenizer(args.tokenizer)
        self.searcher = build_searcher(self.index, self.tokenizer, args)
        self.page_map = build_page_map(self.chunks)
        self.load_s = time.time() - t0
        check_manifest(self.index_path, self.chunks_path, self.chunks,
                       verify=getattr(args, "verify", False))
        print(f"[session] index={self.index_path.name} tokenizer={args.tokenizer} "
              f"chunks={len(self.chunks)} loaded in {self.load_s:.1f}s", file=sys.stderr)
        self.embedder = embedder if embedder is not None else get_embedder(
            prefer=args.embedder, ollama_model=args.ollama_model)

    # -- queries -----------------------------------------------------------------

    def query(self, q: str, final_k: int | None = None, bm25_k: int | None = None,
              alpha: float | None = None, per_file: int | None = None,
              explain: bool = False, dump: int = 0, context: int = 0,
              snippet_width: int = 500) -> dict:
        """One ranked query. Returns a schema-v2 per-query object."""
        a = self.args
        results = hybrid_search(
            q, self.chunks, self.searcher, self.embedder,
            bm25_k=bm25_k if bm25_k is not None else a.bm25_k,
            final_k=final_k if final_k is not None else a.final_k,
            alpha=alpha if alpha is not None else a.alpha,
            per_file=(per_file if per_file is not None else a.per_file) or None,
        )
        hits = [self._hit_payload(c, f, b, d, context, snippet_width)
                for c, f, b, d in results]
        if dump:
            self._attach_dumps(hits, dump)
        out: dict = {"query": q, "hits": hits}
        if explain:
            out["explain"] = explain_terms(self.searcher, self.tokenizer, q)
        if not hits:
            out["hint"] = ("0 results. Try: 'explain' (are the query terms indexed?), "
                           "--mentions TERM (enumerate literal occurrences), or a "
                           "shorter identifier-only query.")
            print(f"[query] 0 hits for {q!r}. Hint: use --explain to see which terms "
                  f"are in the index, or --mentions TERM to enumerate literal matches.",
                  file=sys.stderr)
        return out

    def _hit_payload(self, chunk: Chunk, fused: float, bnorm: float, dnorm: float,
                     context: int = 0, snippet_width: int = 500) -> dict:
        src = rel_source(chunk.source)
        ids = self.page_map.get(src, [])
        try:
            chunk_index = ids.index(chunk.chunk_id)
        except ValueError:
            chunk_index = -1
        snippet, truncated = render_snippet(chunk, self.chunks, self.page_map,
                                            width=snippet_width)
        title = getattr(chunk, "title", "") or Path(src).stem
        doc_type = src.split("/", 1)[0] if src.split("/", 1)[0] in ("Manual", "ScriptReference") else ""
        item: dict = {
            "source": src,
            "title": title,
            "doc_type": doc_type,
            "chunk_id": chunk.chunk_id,
            "chunk_index": chunk_index,
            "n_chunks_in_page": len(ids),
            "fused_score": round(fused, 6),
            "bm25_norm": round(bnorm, 6),
            "dense_norm": round(dnorm, 6),
            "text": snippet,
            "snippet_truncated": truncated,
            "page_text_chars": sum(len(self.chunks[i].text) for i in ids),
            "read_more": f"uv run python dumpdoc.py {src}",
        }
        if context and ids:
            lo = max(0, chunk_index - context)
            hi = min(len(ids), chunk_index + context + 1)
            ctx = []
            for pos in range(lo, hi):
                if pos == chunk_index:
                    continue
                cid = ids[pos]
                csnip, _ = render_snippet(self.chunks[cid], self.chunks, self.page_map,
                                          width=snippet_width)
                ctx.append({"chunk_id": cid, "chunk_index": pos,
                            "context_of": chunk.chunk_id, "text": csnip})
            item["context"] = ctx
        return item

    def _attach_dumps(self, hits: list[dict], dump: int) -> None:
        """Inline full page markdown (dumpdoc.py) for the top *dump* distinct sources."""
        import dumpdoc
        seen: set[str] = set()
        for h in hits:
            if len(seen) >= dump:
                break
            src = h["source"]
            if src in seen:
                continue
            seen.add(src)
            try:
                h["page_markdown"] = dumpdoc.dump(str(resolve_path(src)), heading=False)
            except Exception as exc:
                h["page_markdown_error"] = str(exc)

    # -- mentions / reads ----------------------------------------------------------

    def mentions(self, term: str, limit: int = 60, context: int = 0,
                 dirs: Iterable[str] | None = None) -> dict:
        dirs_n = tuple(_norm_rel(d) for d in dirs) if dirs else None
        return {term: find_mentions(self.chunks, term, limit_files=limit,
                                    context=context, dirs=dirs_n)}

    def read(self, source: str, max_chars: int | None = None) -> dict:
        """Full markdown for one doc page (the 'read_more' action)."""
        import dumpdoc
        path = resolve_path(source)
        if not path.exists():
            return {"source": source, "error": f"not found: {path}"}
        md = dumpdoc.dump(str(path), heading=False)
        out = {"source": rel_source(path), "chars": len(md)}
        if max_chars and len(md) > max_chars:
            out["markdown"] = md[:max_chars]
            out["truncated"] = True
        else:
            out["markdown"] = md
        return out


