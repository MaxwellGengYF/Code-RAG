def main(argv: list[str] | None = None) -> int:
    # Load defaults from retriever_config.json first; CLI args override them.
    pre = argparse.ArgumentParser(add_help=False)
    pre.add_argument("--config", default=DEFAULT_CONFIG_PATH)
    known, _ = pre.parse_known_args(argv)
    config, config_path = load_config(known.config)

    parser = argparse.ArgumentParser(
        description="Hybrid BM25 + dense retrieve over Unity docs (retrieval only, no generation)",
        epilog="Scores are relative ranking signals, not probabilities — fused_score may "
               "exceed 1.0. Snippets are stripped ~500-char previews; follow each hit's "
               "read_more command (or --dump) for the full page. Paths resolve against "
               "the repo root (UNITY_DOCS_ROOT override), so any cwd works.",
    )
    parser.add_argument("--config", default=DEFAULT_CONFIG_PATH, help="Path to JSON config file")
    parser.add_argument("--dirs", nargs="+", default=config.get("dirs"))
    parser.add_argument("--max-files", type=int, default=config.get("max_files", None),
                        help="Limit number of HTML files for quick tests")
    parser.add_argument("--build", action="store_true", help="Build and save the BM25 index")
    parser.add_argument("--force", action="store_true",
                        help="Allow --build to overwrite existing artefacts (required with --max-files)")
    parser.add_argument("--query", action="append", default=None,
                        help="Query string; repeatable — batching in one process is much "
                             "faster than one process per query (index load ~5 s)")
    parser.add_argument("--query-file", default=None,
                        help="File of queries (one per line, '#' comments) - loads the index once")
    parser.add_argument("--repl", action="store_true",
                        help="Persistent session: read JSON requests on stdin "
                             "({'query':...}|{'mentions':...}|{'read':...}), write one JSON "
                             "result per line on stdout. Index loads once.")
    parser.add_argument("--compat", choices=["v1", "v2"], default="v2",
                        help="Output schema: v2 (default, rich hits + _meta) or legacy v1")
    parser.add_argument("--dump", type=int, default=0, metavar="N",
                        help="Inline full page markdown for the top N distinct sources per query")
    parser.add_argument("--context", type=int, default=0, metavar="N",
                        help="Include N neighbour chunks around each hit")
    parser.add_argument("--snippet-width", type=int, default=500,
                        help="Max chars of each hit snippet (boilerplate-stripped)")
    parser.add_argument("--verify", action="store_true",
                        help="Full sha1 manifest check (default: size-based, cheaper)")
    parser.add_argument("--tokenizer", choices=["word", "ngram"], default=config.get("tokenizer", "word"),
                        help="Term model: 'word' (identifier-aware, default) or 'ngram' (legacy)")
    parser.add_argument("--path-boost", type=int, default=config.get("path_boost", 3),
                        help="Repeat doc path/title field terms N times when building (0 disables)")
    parser.add_argument("--fuzziness", default=config.get("fuzziness", 0),
                        help="0 disables fuzzy term expansion (recommended); 'AUTO' is the legacy behaviour")
    parser.add_argument("--min-should-match", type=float,
                        default=config.get("min_should_match", 0.6))
    parser.add_argument("--per-file", type=int, default=config.get("per_file", 1),
                        help="Max chunks per source document in the output (0 = no cap)")
    parser.add_argument("--index-path", default=config["index_path"], help="Index file to load/save")
    parser.add_argument("--chunks-path", default=config["chunks_path"], help="Chunk metadata file")
    parser.add_argument("--bm25-k", type=int, default=config.get("bm25_k", 200),
                        help="BM25 candidates to consider")
    parser.add_argument("--final-k", type=int, default=config.get("final_k", 8))
    parser.add_argument("--alpha", type=float, default=config.get("alpha", 1.0),
                        help="BM25 weight in the fused score (1-alpha is dense weight)")
    parser.add_argument("--embedder", choices=["ollama", "st", "hash", "none"],
                        default=config.get("embedder", "none"))
    parser.add_argument("--ollama-model", default=config.get("ollama_model", "nomic-embed-text"))
    parser.add_argument("--explain", action="store_true",
                        help="With --query: include per-term document frequencies (works "
                             "for any number of queries)")
    parser.add_argument("--mentions", default=None, metavar="TERM",
                        help="List every document literally containing TERM, with counts "
                             "(answers 'which pages mention this symbol at all?'). "
                             "Cannot be combined with --query.")
    parser.add_argument("--mentions-context", type=int, default=0,
                        help="With --mentions: capture N chars of surrounding text per file")
    parser.add_argument("--mentions-limit", type=int, default=60)
    parser.add_argument("--out", default=None, help="Write JSON results to this file "
                        "(relative paths resolve against the current directory)")
    parser.add_argument("--text", action="store_true", help="Print compact human-readable output")
    parser.add_argument("--legacy", action="store_true",
                        help="Force the legacy chunks.pkl/index_word.pkl engine")
    parser.add_argument("--rag", action="store_true",
                        help="Force the RAG engine even if its index is still "
                             "partial (default auto-selects by coverage)")
    args = parser.parse_args(argv)
    args.index_path_explicit = any(
        a.startswith("--index-path") for a in (argv if argv is not None else sys.argv[1:])
    )

    if not args.legacy and not args.build and not args.repl:
        # Default path: delegate to the RAG engine, but only once its index is
        # built AND covers essentially the whole mirror. While `rag.py compile`
        # is still working through the corpus, the legacy artefacts below cover
        # every page and the RAG index would silently retrieve from a subset.
        # --legacy forces this file's original engine; --rag forces the new one.
        from rag.compile import load_rag_config
        from rag.search.engine_select import choose_engine
        rag_cfg = load_rag_config()
        engine_name, status = choose_engine(
            rag_cfg, prefer="rag" if getattr(args, "rag", False) else None)
        if engine_name != "rag":
            if status.get("nothing_built"):
                print(f"[engine] no index built in this checkout: RAG index "
                      f"{status['reason']}; legacy missing "
                      f"{', '.join(status['legacy']['missing'])}. Build with "
                      f"`rag.py compile --provider <cfg> --no-thinking`, or "
                      f"`hybrid_retrieve.py --build --force` for the legacy index.",
                      file=sys.stderr)
            else:
                print(f"[engine] using LEGACY index: RAG index {status['reason']}. "
                      f"Rebuild with `rag.py compile` (then --steps index) to switch.",
                      file=sys.stderr)
        else:
            from rag.cli.search_cmd import run_search
            # Pass every legacy flag through. SA-6 requires "keep every old flag
            # working", and --mentions-context / --mentions-limit / --out /
            # --snippet-width were previously accepted-then-silently-dropped, which
            # is worse than erroring: the output just looks plausible.
            return run_search(
                queries=args.query or [], query_file=args.query_file,
                k=args.final_k, mentions=args.mentions,
                mentions_limit=args.mentions_limit,
                mentions_context=args.mentions_context,
                explain=args.explain, text=args.text, out=args.out,
                snippet_width=args.snippet_width)

    if isinstance(args.fuzziness, str) and args.fuzziness != "AUTO":
        try:
            args.fuzziness = int(args.fuzziness)
        except ValueError:
            pass

    if args.build:
        if args.max_files and not args.force:
            raise SystemExit(
                f"refusing --build --max-files {args.max_files}: this would overwrite "
                f"{args.chunks_path} (currently the full corpus) with a partial set.\n"
                f"Pass --force, or redirect both artefacts, e.g.\n"
                f"  --build --max-files 3000 --chunks-path chunks_smoke.pkl "
                f"--index-path index_smoke.pkl --force"
            )
        chunks = load_chunks(args.dirs, max_files=args.max_files)
        print(f"Loaded {len(chunks)} chunks from {[str(resolve_path(d)) for d in args.dirs]}",
              file=sys.stderr)
        tok = get_tokenizer(args.tokenizer)
        index, searcher = build_bm25_index(chunks, tok, args.path_boost)
        chunks_path = resolve_path(args.chunks_path)
        save_chunks_pickle(chunks, str(chunks_path))
        out_index = (resolve_path(args.index_path) if args.index_path_explicit else
                     resolve_path(config["ngram_index_path"] if args.tokenizer == "ngram"
                                  else config["index_path"]))
        index.save(str(out_index))
        write_manifest(out_index, chunks_path, len(chunks), _n_docs(index),
                       args.tokenizer, args.path_boost)
        print(f"Saved index to {out_index} and chunks to {chunks_path}", file=sys.stderr)

    queries = read_queries(args)

    if args.mentions and queries:
        raise SystemExit("--mentions cannot be combined with --query/--query-file: "
                         "they are different modes (enumeration vs ranking). "
                         "Run them as two separate invocations, or use --repl.")

    if args.mentions:
        chunks_path = resolve_path(args.chunks_path)
        if not chunks_path.exists():
            print(f"artefact not found: {chunks_path}\n  cwd: {Path.cwd()}\n"
                  f"  repo root: {ROOT}\nPaths resolve against the repo root — run from "
                  f"there, set UNITY_DOCS_ROOT, or rebuild with --build.", file=sys.stderr)
            return 1
        chunks = load_chunks_pickle(str(chunks_path))
        res = find_mentions(
            chunks, args.mentions,
            limit_files=args.mentions_limit,
            context=args.mentions_context,
            dirs=tuple(_norm_rel(d) for d in args.dirs) if args.dirs else None,
        )
        if not res:
            print(f"[mentions] 0 files contain {args.mentions!r}. The match is literal "
                  f"(case-insensitive) — check spelling, or try --query for ranked search.",
                  file=sys.stderr)
        out = json.dumps({args.mentions: res}, ensure_ascii=False, indent=2)
        if args.out:
            Path(args.out).write_text(out, encoding="utf-8")
            print(f"wrote {args.out}", file=sys.stderr)
        if args.text:
            print(f"# {args.mentions}: {len(res)} files")
            for r in res:
                print(f"  {r['count']:>4}  {r['source']}")
        else:
            print(out)
        return 0

    if args.repl:
        return repl_loop(args, config)

    if queries:
        try:
            session = Session(args, config)
        except FileNotFoundError as exc:
            print(str(exc), file=sys.stderr)
            return 1
        t0 = time.time()
        per_query = [session.query(q, explain=args.explain, dump=args.dump,
                                   context=args.context,
                                   snippet_width=args.snippet_width)
                     for q in queries]

        if args.compat == "v1":
            # legacy shape: {query: [hits]} (single query: bare list), legacy hit fields
            legacy: dict[str, list[dict]] = {}
            for q, pq in zip(queries, per_query):
                legacy[q] = [{
                    "source": h["source"],
                    "fused_score": h["fused_score"],
                    "bm25_norm": h["bm25_norm"],
                    "dense_norm": h["dense_norm"],
                    "text": h["text"],
                } for h in pq["hits"]]
            payload = legacy if len(queries) > 1 else legacy[queries[0]]
        else:
            payload = {
                "_meta": {
                    "schema": SCHEMA_VERSION,
                    "index": str(session.index_path),
                    "tokenizer": args.tokenizer,
                    "chunks": len(session.chunks),
                    "embedder": args.embedder,
                    "score_note": "relative ranking signal, not a probability; "
                                  "fused_score may exceed 1.0",
                    "elapsed_s": round(time.time() - t0, 3),
                },
                "results": per_query,
            }
        out = json.dumps(payload, ensure_ascii=False, indent=2)
        if args.out:
            Path(args.out).write_text(out, encoding="utf-8")
            print(f"wrote {args.out}", file=sys.stderr)
        if args.text:
            for pq in per_query:
                print(f"\n### {pq['query']}")
                if pq.get("explain"):
                    known = [t["term"] for t in pq["explain"] if t["in_index"]]
                    print(f"  terms in index: {len(known)}/{len(pq['explain'])} {known}")
                for h in pq["hits"]:
                    print(f"  {h['fused_score']:<9.4f} {h['title']}  ({h['source']})")
                    print(f"            {h['text'][:160]}")
        else:
            print(out)

    return 0


def repl_loop(args, config: dict) -> int:
    """Persistent JSONL session: one JSON request per stdin line, one JSON per stdout line.

    Requests:
      {"query": "...", "final_k": 5, "explain": true, "dump": 1, "context": 1, ...}
      {"mentions": "TERM", "limit": 60, "context": 80}
      {"read": "ScriptReference/Rigidbody.AddForce.html", "max_chars": 20000}
    Responses are schema-v2 objects, or {"error": ...} for bad requests.
    """
    try:
        session = Session(args, config)
    except FileNotFoundError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    print("[repl] ready — JSON requests on stdin, one JSON response per line",
          file=sys.stderr, flush=True)
    for line in sys.stdin:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        try:
            req = json.loads(line)
        except json.JSONDecodeError as exc:
            print(json.dumps({"error": f"invalid JSON: {exc}"}), flush=True)
            continue
        try:
            if "query" in req:
                resp = session.query(
                    str(req["query"]),
                    final_k=req.get("final_k"), bm25_k=req.get("bm25_k"),
                    alpha=req.get("alpha"), per_file=req.get("per_file"),
                    explain=bool(req.get("explain", False)),
                    dump=int(req.get("dump", 0)), context=int(req.get("context", 0)),
                    snippet_width=int(req.get("snippet_width", 500)),
                )
                resp["_meta"] = {"schema": SCHEMA_VERSION}
            elif "mentions" in req:
                resp = session.mentions(str(req["mentions"]),
                                        limit=int(req.get("limit", 60)),
                                        context=int(req.get("context", 0)),
                                        dirs=req.get("dirs"))
            elif "read" in req:
                resp = session.read(str(req["read"]), max_chars=req.get("max_chars"))
            else:
                resp = {"error": "request must contain one of: query, mentions, read"}
        except Exception as exc:  # keep the session alive on per-request failures
            resp = {"error": f"{type(exc).__name__}: {exc}"}
        print(json.dumps(resp, ensure_ascii=False), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
