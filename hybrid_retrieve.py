def find_config(path: str) -> Path:
    """Locate the config file: cwd first (explicit override), then the repo root."""
    p = Path(path)
    if p.is_absolute() and p.exists():
        return p
    if p.exists():
        return p.resolve()
    alt = ROOT / path
    return alt.resolve() if alt.exists() else p.resolve()


def load_config(path: str = DEFAULT_CONFIG_PATH) -> tuple[dict, Path]:
    """Load JSON config merged over DEFAULTS. Returns (config, config_file_path)."""
    cfg = dict(DEFAULTS)
    p = find_config(path)
    if p.exists():
        with open(p, "r", encoding="utf-8") as f:
            cfg.update(json.load(f))
    return cfg, p


def resolve_index_path(args, cfg: dict) -> Path:
    """Pick the index file matching the selected tokenizer unless one was given explicitly."""
    if args.index_path_explicit:
        return resolve_path(args.index_path)
    if args.tokenizer == "ngram" or cfg.get("tokenizer") == "ngram":
        return resolve_path(cfg.get("ngram_index_path") or cfg["index_path"])
    return resolve_path(cfg["index_path"])


def build_searcher(index: InvertedIndex, tokenizer, args) -> Searcher:
    """Wrap *index* in a Searcher using the CLI's scoring parameters."""
    return Searcher(
        index,
        tokenizer=tokenizer,
        fuzziness=args.fuzziness,
        min_should_match=args.min_should_match,
    )


def read_queries(args) -> list[str]:
    """Collect queries from (repeatable) --query and/or --query-file."""
    out: list[str] = []
    for q in args.query or []:
        if q and q.strip():
            out.append(q.strip())
    if args.query_file:
        for ln in Path(args.query_file).read_text(encoding="utf-8").splitlines():
            ln = ln.strip()
            if ln and not ln.startswith("#"):
                out.append(ln)
    return out


def explain_terms(searcher: Searcher, tokenizer, query: str, limit: int = 12) -> list[dict]:
    """Report which query terms the index actually knows, with document frequencies."""
    raw = [t for t in dict.fromkeys(tokenizer.tokenize(query))]
    info = []
    for t in raw[:limit]:
        try:
            df = searcher.index.doc_freq(t)
        except Exception:
            df = -1
        info.append({"term": t, "df": df, "in_index": df > 0})
    return info


