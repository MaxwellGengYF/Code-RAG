def get_tokenizer(name: str):
    """Return the tokenizer for *name* ('word' | 'ngram')."""
    if name == "word":
        return WordTokenizer()
    if name == "ngram":
        return NgramTokenizer(n=2)
    raise ValueError(f"unknown tokenizer {name!r} (expected 'word' or 'ngram')")


def doc_tokens(chunk: "Chunk", tok, path_boost: int) -> list[str]:
    """Terms for one chunk: body text plus path/title field terms repeated *path_boost*."""
    toks = tok.tokenize(chunk.text)
    if path_boost and not isinstance(tok, NgramTokenizer):
        toks = toks + path_terms(chunk.source) * path_boost
    return toks


def build_bm25_index(
    chunks: list[Chunk],
    tokenizer=None,
    path_boost: int = 3,
) -> tuple[InvertedIndex, Searcher]:
    """Build a BM25 inverted index over *chunks*."""
    tokenizer = tokenizer or get_tokenizer("word")
    index = InvertedIndex()
    for chunk in tqdm(chunks, desc="Building BM25 index"):
        index.add_document(chunk.chunk_id, doc_tokens(chunk, tokenizer, path_boost))
    index.finalize()
    searcher = Searcher(index, tokenizer=tokenizer, fuzziness=0, min_should_match=0.6)
    return index, searcher


class Embedder:
    """Base embedder interface."""

    def embed(self, texts: list[str]) -> list[np.ndarray]:
        raise NotImplementedError


class OllamaEmbedder(Embedder):
    """Ollama dense embeddings (default: nomic-embed-text)."""

    def __init__(self, model: str = "nomic-embed-text", host: str = "http://localhost:11434"):
        import ollama

        self.model = model
        self.client = ollama.Client(host=host)
        self.dim: int | None = None

    def embed(self, texts: list[str]) -> list[np.ndarray]:
        vectors: list[np.ndarray] = []
        for t in texts:
            # Keep a reasonable length to avoid overloading the context window
            prompt = t[:4000]
            resp = self.client.embeddings(model=self.model, prompt=prompt)
            vec = np.array(resp["embedding"], dtype=np.float32)
            if self.dim is None:
                self.dim = vec.shape[0]
            vectors.append(vec)
        return vectors


class SentenceTransformerEmbedder(Embedder):
    """Fallback local embedder using sentence-transformers (requires network to download model)."""

    def __init__(self, model: str = "all-MiniLM-L6-v2"):
        from sentence_transformers import SentenceTransformer

        self.model = SentenceTransformer(model)
        self.dim = self.model.get_sentence_embedding_dimension()

    def embed(self, texts: list[str]) -> list[np.ndarray]:
        embeddings = self.model.encode(
            texts, convert_to_numpy=True, show_progress_bar=False, normalize_embeddings=False
        )
        return [np.asarray(e, dtype=np.float32) for e in embeddings]


class HashEmbedder(Embedder):
    """Deterministic local dense embedder using hashed n-gram features.

    Works fully offline. NOTE: this is a character-signature model, not a semantic one.
    On the Unity corpus it measured *worse* than pure BM25 (MRR 0.861 -> 0.754), so it is
    no longer used unless explicitly requested.
    """

    def __init__(self, dim: int = 384):
        self.dim = dim

    def _vector(self, text: str) -> np.ndarray:
        v = np.zeros(self.dim, dtype=np.float32)
        norm_text = NgramTokenizer.normalize(text)
        tokens = NgramTokenizer(n=3).tokenize(norm_text)
        for t in tokens:
            h = xxhash.xxh64(t.encode("utf-8")).intdigest()
            # Spread each token across several buckets for smoother signatures
            for i in range(min(8, self.dim)):
                idx = int((h + i * 0x9E3779B97F4A7C15) % self.dim)
                v[idx] += 1.0 if (h >> i) & 1 else -1.0
        norm = np.linalg.norm(v)
        if norm > 0:
            v /= norm
        return v

    def embed(self, texts: list[str]) -> list[np.ndarray]:
        return [self._vector(t) for t in texts]


def cosine_scores(query_emb: np.ndarray, doc_embs: list[np.ndarray]) -> list[float]:
    """Return cosine similarity scores."""
    q = query_emb / (np.linalg.norm(query_emb) + 1e-8)
    scores: list[float] = []
    for emb in doc_embs:
        e = emb / (np.linalg.norm(emb) + 1e-8)
        scores.append(float(np.dot(q, e)))
    return scores


def minmax_normalize(scores: dict[int, float]) -> dict[int, float]:
    vals = list(scores.values())
    if not vals:
        return scores
    min_v, max_v = min(vals), max(vals)
    if max_v == min_v:
        return {k: 1.0 for k in scores}
    return {k: (v - min_v) / (max_v - min_v) for k, v in scores.items()}


def reciprocal_rank(rank: int) -> float:
    return 1.0 / (rank + 60)


def dedupe_by_source(
    ranked: list[int],
    chunks: list["Chunk"],
    per_file: int | None = 1,
) -> list[int]:
    """Keep at most *per_file* chunks per source document, preserving score order."""
    if not per_file:
        return ranked
    seen: dict[str, int] = {}
    out: list[int] = []
    for d in ranked:
        src = Path(str(chunks[d].source)).as_posix()
        n = seen.get(src, 0)
        if n >= per_file:
            continue
        seen[src] = n + 1
        out.append(d)
    return out


def hybrid_search(
    query: str,
    chunks: list[Chunk],
    searcher: Searcher,
    embedder: Embedder | None = None,
    bm25_k: int = 50,
    final_k: int = 5,
    alpha: float = 1.0,
    per_file: int | None = 1,
) -> list[tuple[Chunk, float, float, float]]:
    """BM25 candidate retrieval + optional dense re-rank + linear fusion.

    Returns list of (chunk, fused_score, bm25_norm, dense_norm).
    """
    bm25_results = searcher.search(query, top_k=bm25_k)
    if not bm25_results:
        return []

    bm25_ids = [doc_id for doc_id, _ in bm25_results]
    bm25_scores = {doc_id: score for doc_id, score in bm25_results}
    bm25_norm = minmax_normalize(bm25_scores)

    dense_scores: dict[int, float] = {}
    dense_norm: dict[int, float] = {}
    if embedder is not None and alpha < 1.0:
        candidate_texts = [chunks[i].text for i in bm25_ids]
        query_emb = embedder.embed([query])[0]
        doc_embs = embedder.embed(candidate_texts)
        dense_scores = {i: score for i, score in zip(bm25_ids, cosine_scores(query_emb, doc_embs))}
        dense_norm = minmax_normalize(dense_scores)

    fused: dict[int, float] = {}
    bm25_ranks = {doc_id: rank for rank, doc_id in enumerate(bm25_ids)}
    dense_ranks: dict[int, int] = {}
    if dense_scores:
        dense_order = sorted(bm25_ids, key=lambda x: dense_scores[x], reverse=True)
        dense_ranks = {doc_id: rank for rank, doc_id in enumerate(dense_order)}

    for doc_id in bm25_ids:
        d_norm = dense_norm.get(doc_id, 0.0)
        fused[doc_id] = (
            alpha * bm25_norm[doc_id]
            + (1.0 - alpha) * d_norm
            + 0.01 * reciprocal_rank(bm25_ranks[doc_id])
            + (0.01 * reciprocal_rank(dense_ranks[doc_id]) if dense_ranks else 0.0)
        )

    ranked = heapq.nlargest(len(fused), fused, key=lambda x: (fused[x], -x))
    ranked = dedupe_by_source(ranked, chunks, per_file)[:final_k]
    return [(chunks[i], fused[i], bm25_norm[i], dense_norm.get(i, 0.0)) for i in ranked]


def find_mentions(
    chunks: list["Chunk"],
    term: str,
    *,
    ignore_case: bool = True,
    limit_files: int = 60,
    context: int = 0,
    dirs: tuple[str, ...] | None = None,
) -> list[dict]:
    """Enumerate every document that literally contains *term*, with occurrence counts.

    This is the "which pages mention this symbol at all?" query. BM25 cannot answer it: a
    page that mentions a term once ranks indistinguishably from one that mentions it fifty
    times, and high-frequency generic terms drown the signal. During real doc research this
    enumeration (plus a corpus-wide grep) is what actually finds the authoritative pages.
    """
    needle = term.lower() if ignore_case else term
    per_file: dict[str, int] = {}
    samples: dict[str, str] = {}
    for c in chunks:
        src = str(c.source).replace("\\", "/")
        if dirs and not src.startswith(dirs):
            continue
        hay = c.text.lower() if ignore_case else c.text
        n = hay.count(needle)
        if not n:
            continue
        per_file[src] = per_file.get(src, 0) + n
        if context and src not in samples:
            i = hay.find(needle)
            lo = max(0, i - context)
            samples[src] = re.sub(r"\s+", " ", c.text[lo:i + len(term) + context])
    ranked = heapq.nlargest(limit_files, per_file, key=lambda s: (per_file[s], s))
    return [{"source": s, "count": per_file[s],
             **({"context": samples[s]} if context and s in samples else {})} for s in ranked]


def get_embedder(prefer: str = "none", ollama_model: str = "nomic-embed-text") -> Embedder | None:
    """Return an embedder for *prefer*; ``none`` disables dense re-ranking (the default).

    Falls back to ``None`` (BM25-only) rather than the hash embedder when a requested
    backend is unreachable, because the hash signature embedder measurably degrades
    ranking on this corpus.
    """
    if prefer in ("none", "", None):
        return None
    if prefer == "st":
        return SentenceTransformerEmbedder()
    if prefer == "hash":
        print("[embedder] 'hash' is a character-signature model and hurts ranking here; "
              "prefer 'none', 'ollama' or 'st'.", file=sys.stderr)
        return HashEmbedder()
    if prefer == "ollama":
        try:
            emb = OllamaEmbedder(model=ollama_model)
            emb.embed(["hello"])  # connectivity check
            print(f"[embedder] Using Ollama model '{ollama_model}'", file=sys.stderr)
            return emb
        except Exception as exc:
            print(f"[embedder] Ollama unavailable ({exc}); falling back to BM25-only",
                  file=sys.stderr)
    return None


# --------------------------------------------------------------------------------------
# Build manifest: one manifest.json at ROOT, keyed by index file name, so a stale or
# mismatched (index, chunks) pair is caught loudly instead of silently mis-ranking.
# --------------------------------------------------------------------------------------


def _sha1_8(path: Path) -> str:
    h = hashlib.sha1()
    with open(path, "rb") as f:
        for blk in iter(lambda: f.read(1 << 20), b""):
            h.update(blk)
    return h.hexdigest()[:8]


def _n_docs(index: InvertedIndex) -> int:
    try:
        return len(index._doc_lengths)
    except Exception:
        return -1


def write_manifest(
    index_path: Path,
    chunks_path: Path,
    n_chunks: int,
    n_docs: int,
    tokenizer: str,
    path_boost: int,
) -> None:
    """Record build metadata for *index_path* in ROOT/manifest.json."""
    mf = resolve_path(MANIFEST_PATH)
    data = {"indices": {}}
    if mf.exists():
        try:
            data = json.loads(mf.read_text(encoding="utf-8"))
            data.setdefault("indices", {})
        except Exception:
            pass
    entry = {
        "built_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "tokenizer": tokenizer,
        "path_boost": path_boost,
        "n_chunks": n_chunks,
        "n_docs_indexed": n_docs,
        "chunks_path": rel_source(chunks_path),
        "chunks_size": chunks_path.stat().st_size,
        "chunks_sha1_8": _sha1_8(chunks_path),
        "index_size": index_path.stat().st_size,
        "index_sha1_8": _sha1_8(index_path),
    }
    data["indices"][index_path.name] = entry
    mf.write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"updated {mf.name} entry for {index_path.name}", file=sys.stderr)


def check_manifest(
    index_path: Path,
    chunks_path: Path,
    chunks: list["Chunk"],
    verify: bool = False,
) -> None:
    """Warn (stderr, non-fatal) when the loaded artefacts look stale or mismatched.

    Default check is size-based (cheap); ``verify=True`` also compares sha1.
    """
    mf = resolve_path(MANIFEST_PATH)
    warn: list[str] = []
    if not mf.exists():
        warn.append(f"no {MANIFEST_PATH} at {mf} — artefacts predate manifest tracking; "
                    f"rebuild with --build --force to enable staleness checks")
    else:
        try:
            entry = json.loads(mf.read_text(encoding="utf-8"))["indices"].get(index_path.name)
        except Exception as exc:
            entry = None
            warn.append(f"could not parse {MANIFEST_PATH}: {exc}")
        if entry is None and mf.exists():
            warn.append(f"{MANIFEST_PATH} has no entry for {index_path.name} "
                        f"(built by another tool?); rebuild with --build --force")
        elif entry is not None:
            if entry.get("n_chunks") != len(chunks):
                warn.append(f"manifest says {entry.get('n_chunks')} chunks but "
                            f"{chunks_path.name} loaded {len(chunks)} — chunks/index mismatch")
            if entry.get("chunks_path") and rel_source(chunks_path) != entry["chunks_path"]:
                warn.append(f"chunks file is {rel_source(chunks_path)} but manifest expects "
                            f"{entry['chunks_path']}")
            if entry.get("index_size") != index_path.stat().st_size:
                warn.append(f"{index_path.name} size changed since build "
                            f"({entry.get('index_size')} -> {index_path.stat().st_size})")
            if entry.get("chunks_size") != chunks_path.stat().st_size:
                warn.append(f"{chunks_path.name} size changed since build "
                            f"({entry.get('chunks_size')} -> {chunks_path.stat().st_size})")
            if verify:
                if entry.get("index_sha1_8") != _sha1_8(index_path):
                    warn.append(f"{index_path.name} sha1 mismatch vs manifest")
                if entry.get("chunks_sha1_8") != _sha1_8(chunks_path):
                    warn.append(f"{chunks_path.name} sha1 mismatch vs manifest")
    for w in warn:
        print(f"[manifest] WARNING: {w}", file=sys.stderr)


